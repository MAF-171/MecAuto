package pe.mecauto.dao;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Prueba del DAO contra H2 en memoria (solo para pruebas; la aplicación usa SQL Server).
 * Cada prueba crea su propia base para que no dependan entre sí.
 */
class ClienteDAOImplTest {

    private ClienteDAO dao;
    private long idJuan;

    @BeforeEach
    void preparar() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:dao_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE cliente (id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "nro_documento VARCHAR(12) NOT NULL)");
        jdbc.update("INSERT INTO cliente (nro_documento) VALUES (?)", "12345678");
        jdbc.update("INSERT INTO cliente (nro_documento) VALUES (?)", "20123456789");
        idJuan = jdbc.queryForObject("SELECT id_cliente FROM cliente WHERE nro_documento = ?", Long.class, "12345678");
        dao = new ClienteDAOImpl(jdbc);
    }

    @Test
    @DisplayName("existePorDocumento: encuentra uno existente y no uno nuevo")
    void existePorDocumento() {
        assertTrue(dao.existePorDocumento("12345678"));
        assertTrue(dao.existePorDocumento("20123456789"));
        assertFalse(dao.existePorDocumento("87654321"));
    }

    @Test
    @DisplayName("existeOtroConDocumento: el propio cliente no cuenta como duplicado")
    void existeOtroConDocumento() {
        assertFalse(dao.existeOtroConDocumento("12345678", idJuan), "su propio documento no es un duplicado");
        assertTrue(dao.existeOtroConDocumento("12345678", idJuan + 100), "otro cliente con el mismo documento sí lo es");
        assertFalse(dao.existeOtroConDocumento("87654321", idJuan));
    }

    @Test
    @DisplayName("Un texto con comillas se trata como dato, no como SQL (consulta parametrizada)")
    void noEsVulnerableAInyeccion() {
        assertFalse(dao.existePorDocumento("' OR '1'='1"));
    }
}
